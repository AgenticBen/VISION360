#!/usr/bin/env node
// Corpus lock: records exactly which data and rules the site and demo run on.
//
//   npm run lock                         write data/corpus.lock.json
//   node scripts/corpus-lock.mjs --check fail if the files differ from the lock
//
// Changing a record, a question or the engine is allowed. It just has to be
// deliberate: run `npm run lock`, review the lock diff and the golden routing
// test output (`npm run test:demo`), and commit them together.
//
// Zero dependencies.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";

const LOCK = "data/corpus.lock.json";
const FILES = [
  "data/organizations.json",
  "site/data/organizations.json",
  "site/data/assessment.json",
  "site/data/geography.json",
  "site/data/pathways.json",
  "site/quiz-engine.js",
];

function current() {
  const files = {};
  for (const f of FILES) files[f] = createHash("sha256").update(readFileSync(f)).digest("hex");
  const orgs = JSON.parse(readFileSync("site/data/organizations.json", "utf8"));
  const assessment = JSON.parse(readFileSync("site/data/assessment.json", "utf8"));
  return {
    _comment: "Generated by `npm run lock`. Review this diff whenever data or rules change.",
    files,
    counts: {
      organizations: orgs.length,
      questions: (assessment.questions || []).length,
      handoffs: (assessment.handoffs || []).length,
    },
  };
}

const now = current();

if (process.argv.includes("--check")) {
  if (!existsSync(LOCK)) {
    console.error(`FAIL: ${LOCK} is missing. Run \`npm run lock\` and commit it.`);
    process.exit(1);
  }
  const lock = JSON.parse(readFileSync(LOCK, "utf8"));
  const changed = FILES.filter((f) => (lock.files || {})[f] !== now.files[f]);
  if (changed.length) {
    console.error("FAIL: data or rules changed since the last lock:");
    for (const f of changed) console.error(`  - ${f}`);
    console.error("\nIf this change is intended: run `npm run lock`, check the golden routing");
    console.error("output from `npm run test:demo`, and commit the lock with the change.\n");
    process.exit(1);
  }
  console.log(`  Corpus lock matches (${now.counts.organizations} organizations, ${now.counts.questions} questions).`);
} else {
  writeFileSync(LOCK, JSON.stringify(now, null, 2) + "\n");
  console.log(`Wrote ${LOCK}: ${now.counts.organizations} organizations, ${now.counts.questions} questions, ${now.counts.handoffs} handoffs.`);
}
